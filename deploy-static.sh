#!/usr/bin/env bash
# 匯出純靜態網站（GitHub Pages／Cloudflare Pages／Netlify）。不含伺服器、帳號資料與教材。
# bash deploy-static.sh [--out 輸出資料夾]   預設 github-pages/
set -euo pipefail
TASK_ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
OUTPUT_DIR="$TASK_ROOT/github-pages"
while [[ $# -gt 0 ]]; do
  case "$1" in
    --out) OUTPUT_DIR="$2"; shift 2;;
    -h|--help) echo '使用：bash deploy-static.sh [--out 資料夾]'; exit 0;;
    *) echo "未知選項：$1" >&2; exit 2;;
  esac
done
command -v python3 >/dev/null || { echo '需要 Python 3.10+' >&2; exit 1; }
python3 "$TASK_ROOT/tools/check_offline.py"
python3 - "$TASK_ROOT" "$OUTPUT_DIR" <<'PY'
import pathlib, shutil, sys, tempfile
root = pathlib.Path(sys.argv[1]).resolve(); output = pathlib.Path(sys.argv[2]).resolve()
source = root / 'public' / 'academy'
if output == root or output == source or output in source.parents or source in output.parents:
    sys.exit('輸出目錄不可為專案根目錄、來源或其上下層。')
marker = '.huatuo-static-export'
if output.exists() and not (output / marker).is_file():
    sys.exit('輸出目錄已存在且非本腳本產生；請改用新目錄。')
output.parent.mkdir(parents=True, exist_ok=True)
tmp = pathlib.Path(tempfile.mkdtemp(prefix='huatuo-export-', dir=output.parent))
try:
    shutil.copytree(source, tmp, dirs_exist_ok=True, ignore=shutil.ignore_patterns('.env*', '.git', '__pycache__', '*.pyc', '*.sqlite*', '*.pem', '*.key'))
    (tmp / '.nojekyll').write_text('', encoding='utf-8')
    (tmp / marker).write_text('Generated by deploy-static.sh\n', encoding='utf-8')
    # Force static mode so the page never waits for an API on a static host.
    cfg = tmp / 'config.js'
    cfg.write_text(cfg.read_text(encoding='utf-8').replace("siteMode: 'auto'", "siteMode: 'static'"), encoding='utf-8')
    if output.exists(): shutil.rmtree(output)
    tmp.replace(output)
finally:
    if tmp.exists(): shutil.rmtree(tmp)
print('靜態網站已完成：' + str(output))
print('靜態版可閱讀全部課程並保存本機進度；驗證帳號、付款與 AI 師傅需 run-local.sh 伺服器。')
PY
